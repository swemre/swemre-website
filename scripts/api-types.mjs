// FR-API-013 Writes the website's wire types from the public API's committed v1 contract
// (openapi-v1.json in the API repository, or API_SPEC: a file path or an https URL of
// /api/public/v1/openapi.json, which needs no key). The file is written only when the whole
// generation succeeds; regenerate it in the same change as any contract change.
import {mkdirSync, writeFileSync} from 'node:fs'
import {resolve} from 'node:path'
import {pathToFileURL} from 'node:url'
import openapiTS, {astToString} from 'openapi-typescript'

const DEFAULT_SPEC =
  '../swemre-website-api/modules/api/service/src/main/resources/openapi-v1.json'
const spec = process.env.API_SPEC ?? DEFAULT_SPEC
const source = /^https?:\/\//.test(spec)
  ? new URL(spec)
  : pathToFileURL(resolve(spec))
const target = new URL('../src/contract/generated/api-v1.d.ts', import.meta.url)

const ast = await openapiTS(source)
const header =
  "// Generated by scripts/api-types.mjs from the API's openapi-v1.json; " +
  'run npm run api:types.\n'
mkdirSync(new URL('.', target), {recursive: true})
writeFileSync(target, header + astToString(ast))
console.log(`Wrote src/contract/generated/api-v1.d.ts from ${spec}`)
